# Generates Source\UI\Material\IconData.cpp: the SVG path data of the MaterialDesign PackIcon kinds
# the manager uses (Material Design Icons, Apache 2.0), read from MaterialDesignThemes.Wpf.dll in the
# NuGet cache. Run it by hand after adding an icon to $Kinds; the output is committed, not built.
param(
    [string]$ProjectDir = (Split-Path -Parent $PSScriptRoot),
    [string]$Dll = (Join-Path $env:USERPROFILE '.nuget\packages\materialdesignthemes\5.1.0\lib\net462\MaterialDesignThemes.Wpf.dll')
)

$ErrorActionPreference = 'Stop'

# Every Kind="..." in the old XAML plus the ones the C# picked in code
$Kinds = @(
    'Account', 'AccountCircle', 'AccountConvert', 'AccountSwitch', 'AlertCircle', 'AlertOutline', 'ArrowDown', 'ArrowLeft', 'ArrowRight',
    'ArrowUp', 'AutoFix', 'BackupRestore', 'Bug', 'Check', 'CheckAll', 'CheckboxBlankOutline', 'CheckboxMarked', 'CheckCircle',
    'CheckCircleOutline', 'CheckDecagram', 'ChevronLeft', 'ChevronRight', 'ClipboardTextClockOutline', 'ClockOutline', 'Close', 'CloseCircle', 'Cloud',
    'CloudDownload', 'CloudSearch', 'Cog', 'ContentSave', 'ContentSaveAll', 'Counter', 'CursorPointer', 'Delete', 'Download',
    'DragVertical', 'Export', 'File', 'FileDocumentOutline', 'FileImport', 'FileMultiple', 'Flash', 'Folder', 'FolderCog',
    'FolderMultiple', 'FolderOpen', 'FormatListNumbered', 'ImagePlus', 'Import', 'Information', 'InformationOutline', 'Link', 'LinkOff',
    'Lock', 'Magnify', 'Memory', 'MenuDown', 'Palette', 'PlusCircle', 'Puzzle', 'Refresh', 'Restore',
    'RestoreAlert', 'Rocket', 'Send', 'ShieldLock', 'Snowflake', 'Star', 'StarCircle', 'Steam', 'SwapHorizontal',
    'TrendingUp', 'TrophyAward', 'WeatherNight', 'WeatherSunny', 'Web', 'Wrench',
    # Mod Store
    'Storefront', 'Heart', 'Eye', 'OpenInNew', 'Sort', 'ImageOff', 'PageNext', 'PagePrevious', 'PackageDown', 'CheckboxMarkedCircle'
) | Sort-Object -Unique

$asm = [System.Reflection.Assembly]::LoadFrom($Dll)
$factory = $asm.GetType('MaterialDesignThemes.Wpf.PackIconDataFactory')
$create = $factory.GetMethod('Create', [System.Reflection.BindingFlags]'Static,Public,NonPublic')
$data = $create.Invoke($null, @())
$kindType = $asm.GetType('MaterialDesignThemes.Wpf.PackIconKind')

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// Generated by Tools\ExtractMaterialIcons.ps1 - do not edit.')
[void]$sb.AppendLine('// SVG path data (24x24 viewbox) of the MaterialDesign PackIcon kinds the manager uses.')
[void]$sb.AppendLine('#include "UI/Material/PackIcon.h"')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('namespace SonicRacingSaveManager::UI::Material {')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('const char* IconPathData(Icon icon) {')
[void]$sb.AppendLine('    switch (icon) {')
foreach ($k in $Kinds) {
    $kind = [Enum]::Parse($kindType, $k)
    $path = $data[$kind]
    [void]$sb.AppendLine("        case Icon::$($k): return `"$path`";")
}
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('    return "";')
[void]$sb.AppendLine('}')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('} // namespace SonicRacingSaveManager::UI::Material')

$enum = New-Object System.Text.StringBuilder
[void]$enum.AppendLine('// Generated by Tools\ExtractMaterialIcons.ps1 - do not edit.')
[void]$enum.AppendLine('#pragma once')
[void]$enum.AppendLine('')
[void]$enum.AppendLine('namespace SonicRacingSaveManager::UI::Material {')
[void]$enum.AppendLine('')
[void]$enum.AppendLine('// MaterialDesign PackIconKind values used by the manager')
[void]$enum.AppendLine('enum class Icon {')
foreach ($k in $Kinds) { [void]$enum.AppendLine("    $k,") }
[void]$enum.AppendLine('};')
[void]$enum.AppendLine('')
[void]$enum.AppendLine('} // namespace SonicRacingSaveManager::UI::Material')

$outDir = Join-Path $ProjectDir 'Source\UI\Material'
New-Item -ItemType Directory -Force -Path $outDir | Out-Null
[System.IO.File]::WriteAllText((Join-Path $outDir 'IconData.cpp'), $sb.ToString(), (New-Object System.Text.UTF8Encoding $false))
[System.IO.File]::WriteAllText((Join-Path $outDir 'IconKind.h'), $enum.ToString(), (New-Object System.Text.UTF8Encoding $false))
Write-Host "ExtractMaterialIcons: $($Kinds.Count) icons"
