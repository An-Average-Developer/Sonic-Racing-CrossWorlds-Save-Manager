# Generates the resource script that embeds everything under Assets\ and Translations\ into the exe,
# plus the table Services\App\ResourceExtractor uses to unpack them to %TEMP%\SonicRacingSaveManager on startup.
# Runs as a pre-build step; only rewrites the outputs when the file list changed.
param([Parameter(Mandatory = $true)][string]$ProjectDir)

$ErrorActionPreference = 'Stop'
$ProjectDir = (Resolve-Path -LiteralPath $ProjectDir).Path.TrimEnd('\')   # MSBuild passes "<dir>\."
$outDir = Join-Path $ProjectDir 'Resources\Generated'
New-Item -ItemType Directory -Force -Path $outDir | Out-Null

$roots = @(
    @{ Name = 'Assets'; Path = Join-Path $ProjectDir 'Assets'; Skip = @('Icons') },        # icons are ICON resources (App.rc)
    @{ Name = 'Translations'; Path = Join-Path $ProjectDir 'Translations'; Skip = @() }
)

$entries = @()
$id = 1000
foreach ($root in $roots) {
    if (-not (Test-Path $root.Path)) { continue }
    Get-ChildItem -Path $root.Path -Recurse -File | Sort-Object FullName | ForEach-Object {
        $relative = $_.FullName.Substring($root.Path.Length + 1)
        $top = $relative.Split('\')[0]
        if ($root.Skip -contains $top) { return }
        $entries += [pscustomobject]@{ Id = $id; Root = $root.Name; Relative = $relative; Full = $_.FullName; Size = $_.Length; Stamp = $_.LastWriteTimeUtc.Ticks }
        $id++
    }
}

$rc = New-Object System.Text.StringBuilder
[void]$rc.AppendLine('// Generated by Tools\GenerateAssets.ps1 - do not edit.')
foreach ($e in $entries) {
    $path = $e.Full.Replace('\', '\\')
    [void]$rc.AppendLine("$($e.Id) RCDATA `"$path`"")
}

$h = New-Object System.Text.StringBuilder
[void]$h.AppendLine('// Generated by Tools\GenerateAssets.ps1 - do not edit.')
[void]$h.AppendLine('#pragma once')
[void]$h.AppendLine('')
[void]$h.AppendLine('struct EmbeddedAsset { int id; const wchar_t* root; const wchar_t* path; };')
[void]$h.AppendLine('')
[void]$h.AppendLine('inline constexpr EmbeddedAsset kEmbeddedAssets[] = {')
foreach ($e in $entries) {
    $rel = $e.Relative.Replace('\', '\\')
    [void]$h.AppendLine("    { $($e.Id), L`"$($e.Root)`", L`"$rel`" },")
}
[void]$h.AppendLine('};')
# A stamp of the embedded content, so the extractor can skip unchanged files between runs
$hash = [System.BitConverter]::ToString(
    [System.Security.Cryptography.SHA256]::Create().ComputeHash(
        [System.Text.Encoding]::UTF8.GetBytes((($entries | ForEach-Object { "$($_.Relative)|$($_.Size)|$($_.Stamp)" }) -join "`n")))).Replace('-', '').Substring(0, 16)
[void]$h.AppendLine("inline constexpr const wchar_t* kEmbeddedAssetsStamp = L`"$hash`";")

function Write-IfChanged([string]$path, [string]$content) {
    if ((Test-Path $path) -and ((Get-Content -Raw -Path $path) -eq $content)) { return }
    [System.IO.File]::WriteAllText($path, $content, (New-Object System.Text.UTF8Encoding $false))
    Write-Host "GenerateAssets: wrote $path"
}

Write-IfChanged (Join-Path $outDir 'Assets.rc') $rc.ToString()
Write-IfChanged (Join-Path $outDir 'AssetTable.h') $h.ToString()
Write-Host "GenerateAssets: $($entries.Count) embedded files"
