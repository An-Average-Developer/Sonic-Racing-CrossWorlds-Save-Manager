Group GroupOf(int id) {
    const int pack = Pack(id);
    // The base game: characters (10xxx) and designs
    if (pack == 0) return id >= 10000 && id < 20000 ? Group::Characters : Group::Designs;
    // The brand campaigns
    if (pack >= 100) return Group::Brands;
    // The World Championship 2026 and an esports team (Crazy Raccoon)
    if (pack == 44 || pack == 26) return Group::Competitions;
    // The festivals (collabs), SEGA's arcade games and consoles
    return Group::Events;
}

